package main

import (
	"bytes"
	"fmt"
	"go/format"
	"maps"
	"slices"
	"strings"
)

const header = "// Code generated by teleiq-gen. DO NOT EDIT.\n\n"

// generate renders every file of the model, keyed by file name.
func generate(m *model) (map[string][]byte, error) {
	files := map[string][]byte{}
	add := func(name string, src *source) error {
		if _, dup := files[name]; dup {
			return fmt.Errorf("two outputs are named %s", name)
		}
		out, err := src.format()
		if err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
		files[name] = out
		return nil
	}
	sections, err := renderSections(m)
	if err != nil {
		return nil, err
	}
	for _, name := range slices.Sorted(maps.Keys(sections)) {
		if err := add(name, sections[name]); err != nil {
			return nil, err
		}
	}
	version := newSource()
	version.doc("", "SupportedBotAPIVersion is the Telegram Bot API version that this package implements.")
	version.line("const SupportedBotAPIVersion = %q", m.version)
	if err := add("version.gen.go", version); err != nil {
		return nil, err
	}
	sends, err := contextSends(m.methods)
	if err != nil {
		return nil, err
	}
	if err := add(contextFile, renderContextSends(sends)); err != nil {
		return nil, err
	}
	return files, nil
}

// The files of package teleiq that hold the methods of Client and their parameters.
const (
	methodsFile = "methods.gen.go"
	paramsFile  = "methods_params.gen.go"
)

// renderSections renders the models types and Client methods, keyed by file name.
func renderSections(m *model) (map[string]*source, error) {
	files := map[string]*source{}
	appendTo := func(name, pkg string, src *source) {
		dst := files[name]
		if dst == nil {
			dst = newSource()
			dst.pkg = pkg
			files[name] = dst
		} else {
			dst.body.WriteString("\n")
		}
		dst.body.Write(src.body.Bytes())
		for path := range src.imports {
			dst.imports[path] = true
		}
	}
	// Package teleiq decodes returned unions, so models exports their decoding.
	returned := map[string]bool{}
	for _, meth := range m.methods {
		if meth.result == resultUnion || meth.result == resultUnions {
			returned[meth.union] = true
		}
	}
	addUnion := func(u *union, section string) error {
		src, err := renderUnion(u)
		if err != nil {
			return err
		}
		if returned[u.name] {
			renderExportedDecode(src, u)
		}
		file, err := sectionFile(section)
		if err != nil {
			return fmt.Errorf("type %s: %w", u.name, err)
		}
		appendTo(file, "models", src)
		return nil
	}
	objects := map[string]*object{}
	for _, o := range m.objects {
		objects[o.name] = o
	}
	for _, name := range m.page {
		section := m.types[name].Section
		switch {
		case objects[name] != nil:
			file, err := sectionFile(section)
			if err != nil {
				return nil, fmt.Errorf("type %s: %w", name, err)
			}
			appendTo(file, "models", renderObject(objects[name]))
		case m.unions[name] != nil:
			if err := addUnion(m.unions[name], section); err != nil {
				return nil, err
			}
		}
	}
	for _, u := range m.order {
		if u.synthetic {
			if err := addUnion(u, m.types[u.members[0].name].Section); err != nil {
				return nil, err
			}
		}
	}
	for _, meth := range m.methods {
		appendTo(methodsFile, "teleiq", renderMethod(meth))
		if meth.params != nil {
			appendTo(paramsFile, "teleiq", renderObject(meth.params))
		}
	}
	appendTo(paramsFile, "teleiq", renderCollectModel(m))
	return files, nil
}

// renderExportedDecode writes the exported decoding of a union that a method returns.
func renderExportedDecode(s *source, u *union) {
	s.line("")
	s.doc("", fmt.Sprintf("Decode%s decodes a %s from JSON, choosing its concrete type, as package teleiq does for the result of a method.", u.name, u.name))
	s.line("func Decode%s(data []byte) (%s, error) { return decode%s(data) }", u.name, u.name, u.name)
}

// source is a generated Go file, of package teleiq unless pkg says otherwise.
type source struct {
	pkg     string
	body    bytes.Buffer
	imports map[string]bool
}

func newSource() *source {
	return &source{pkg: "teleiq", imports: map[string]bool{}}
}

// qualify returns typ with the names of package models qualified.
func (s *source) qualify(typ string) string {
	base := strings.TrimLeft(typ, "*[]")
	switch base {
	case "string", "bool", "int", "int64", "float64":
		return typ
	}
	s.imports[modelsPath] = true
	return typ[:len(typ)-len(base)] + "models." + base
}

func (s *source) line(format string, args ...any) {
	fmt.Fprintf(&s.body, format, args...)
	s.body.WriteByte('\n')
}

// doc writes text as a comment wrapped near 100 columns.
func (s *source) doc(indent, text string) {
	const width = 100
	line := indent + "//"
	for word := range strings.FieldsSeq(text) {
		if len(line)+1+len(word) > width && line != indent+"//" {
			s.body.WriteString(line + "\n")
			line = indent + "//"
		}
		line += " " + word
	}
	s.body.WriteString(line + "\n")
}

func (s *source) format() ([]byte, error) {
	var out bytes.Buffer
	out.WriteString(header + "package " + s.pkg + "\n\n")
	switch len(s.imports) {
	case 0:
	case 1:
		for path := range s.imports {
			fmt.Fprintf(&out, "import %q\n\n", path)
		}
	default:
		// Like goimports, set the imports of other modules apart from the standard library.
		var std, other []string
		for _, path := range slices.Sorted(maps.Keys(s.imports)) {
			if first, _, _ := strings.Cut(path, "/"); strings.Contains(first, ".") {
				other = append(other, path)
			} else {
				std = append(std, path)
			}
		}
		out.WriteString("import (\n")
		for _, path := range std {
			fmt.Fprintf(&out, "\t%q\n", path)
		}
		if len(std) > 0 && len(other) > 0 {
			out.WriteString("\n")
		}
		for _, path := range other {
			fmt.Fprintf(&out, "\t%q\n", path)
		}
		out.WriteString(")\n\n")
	}
	out.Write(s.body.Bytes())
	return format.Source(out.Bytes())
}
