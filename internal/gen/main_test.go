func TestRun(t *testing.T) {
	api := loadAPI(t)
	first, second := t.TempDir(), t.TempDir()
	stale := []string{filepath.Join(second, "models", "removedsection.gen.go")}
	kept := filepath.Join(second, "client.go")
	if err := os.MkdirAll(filepath.Join(second, "models"), 0o755); err != nil {
		t.Fatal(err)
	}
	for _, path := range append(stale, kept) {
		if err := os.WriteFile(path, []byte("package teleiq\n"), 0o644); err != nil {
			t.Fatal(err)
		}
	}

	for _, dir := range []string{first, second} {
		if err := run(snapshotPath, dir, false); err != nil {
			t.Fatalf("run() error = %v", err)
		}
	}

	for _, path := range stale {
		if _, err := os.Stat(path); !os.IsNotExist(err) {
			t.Errorf("stale generated file %s was not removed: %v", filepath.Base(path), err)
		}
	}
	if _, err := os.Stat(kept); err != nil {
		t.Errorf("a file that is not generated was touched: %v", err)
	}
	firstFiles, _ := filepath.Glob(filepath.Join(first, "*.gen.go"))
	modelFiles, _ := filepath.Glob(filepath.Join(first, "models", "*.gen.go"))
	firstFiles = append(firstFiles, modelFiles...)
	if _, err := os.Stat(filepath.Join(first, contextFile)); err != nil {
		t.Errorf("the send methods of bot.Context are not generated: %v", err)
	}
	firstFiles = append(firstFiles, filepath.Join(first, contextFile))
	sections := map[string]bool{}
	for _, ty := range api.Types {
		sections[ty.Section] = true
	}
	// A file of models for each section, the methods and their parameters, the version, and the
	// send methods of bot.Context.
	if want := len(sections) + 4; len(firstFiles) != want {
		t.Errorf("run() wrote %d files, want %d", len(firstFiles), want)
	}
	declared := func(name, decl string) bool {
		t.Helper()
		src, _ := os.ReadFile(filepath.Join(first, name))
		return strings.Count(string(src), "\n"+decl) == 1
	}
	typeFile := func(section string) string {
		t.Helper()
		name, err := sectionFile(section)
		if err != nil {
			t.Fatal(err)
		}
		return name
	}
	for _, ty := range api.Types {
		if got := declared(typeFile(ty.Section), "type "+ty.Name+" "); got == handwritten[ty.Name] {
			t.Errorf("type %s: declared once in the file of %q = %v, want %v", ty.Name, ty.Section, got, !handwritten[ty.Name])
		}
	}
	for _, s := range synthetic {
		if !declared(typeFile("Available types"), "type "+s.name+" ") {
			t.Errorf("the synthetic union %s is not in the file of the section of its first member", s.name)
		}
	}
	for _, meth := range api.Methods {
		if !declared(methodsFile, "func (c *Client) "+upperFirst(meth.Name)+"(") {
			t.Errorf("method %s is not declared once in %s", meth.Name, methodsFile)
		}
		if len(meth.Params) > 0 && !declared(paramsFile, "type "+upperFirst(meth.Name)+"Params struct") {
			t.Errorf("the parameters of %s are not declared once in %s", meth.Name, paramsFile)
		}
	}
	for _, path := range firstFiles {
		a, _ := os.ReadFile(path)
		rel, _ := filepath.Rel(first, path)
		b, err := os.ReadFile(filepath.Join(second, rel))
		if err != nil || !bytes.Equal(a, b) {
			t.Errorf("%s differs between two runs", rel)
		}
		if !strings.HasPrefix(string(a), "// Code generated by teleiq-gen. DO NOT EDIT.\n") {
			t.Errorf("%s has no generated-code header", rel)
		}
	}
}

func TestRunErrors(t *testing.T) {
	bad := filepath.Join(t.TempDir(), "bad.json")
	if err := os.WriteFile(bad, []byte(`{"version":"1.0","unknown":1}`), 0o644); err != nil {
		t.Fatal(err)
	}
	tests := []struct{ name, schema, wantErr string }{
		{"missing snapshot", filepath.Join(t.TempDir(), "none.json"), "no such file"},
		{"invalid snapshot", bad, "bad.json"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if err := run(tt.schema, t.TempDir(), false); err == nil || !strings.Contains(err.Error(), tt.wantErr) {
				t.Fatalf("run() error = %v, want one containing %q", err, tt.wantErr)
			}
		})
	}
}

func TestRunCheck(t *testing.T) {
	tests := []struct {
		name    string
		change  func(dir string) error
		wantErr string
	}{
		{name: "up to date", change: func(string) error { return nil }},
		{
			name: "other files are ignored",
			change: func(dir string) error {
				return os.WriteFile(filepath.Join(dir, "client.go"), []byte("package teleiq\n"), 0o644)
			},
		},
		{
			name: "edited by hand",
			change: func(dir string) error {
				return os.WriteFile(filepath.Join(dir, "models", "available.gen.go"), []byte("package models\n"), 0o644)
			},
			wantErr: "models/available.gen.go differs",
		},
		{
			name: "send methods of bot.Context edited by hand",
			change: func(dir string) error {
				return os.WriteFile(filepath.Join(dir, contextFile), []byte("package bot\n"), 0o644)
			},
			wantErr: "bot/context_send.gen.go differs",
		},
		{
			name:    "send methods of bot.Context missing",
			change:  func(dir string) error { return os.Remove(filepath.Join(dir, contextFile)) },
			wantErr: "bot/context_send.gen.go is missing",
		},
		{
			name:    "missing",
			change:  func(dir string) error { return os.Remove(filepath.Join(dir, "methods_params.gen.go")) },
			wantErr: "methods_params.gen.go is missing",
		},
		{
			name: "no longer generated",
			change: func(dir string) error {
				return os.WriteFile(filepath.Join(dir, "models", "removedsection.gen.go"), []byte("package models\n"), 0o644)
			},
			wantErr: "models/removedsection.gen.go is no longer generated",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			dir := t.TempDir()
			if err := run(snapshotPath, dir, false); err != nil {
				t.Fatal(err)
			}
			if err := tt.change(dir); err != nil {
				t.Fatal(err)
			}
			before, _ := os.ReadDir(dir)

			err := run(snapshotPath, dir, true)

			if tt.wantErr == "" && err != nil {
				t.Fatalf("run(check) error = %v", err)
			}
			if tt.wantErr != "" && (err == nil || !strings.Contains(err.Error(), tt.wantErr) || !strings.Contains(err.Error(), "go generate")) {
				t.Fatalf("run(check) error = %v, want one naming %q and go generate", err, tt.wantErr)
			}
			if after, _ := os.ReadDir(dir); len(after) != len(before) {
				t.Errorf("run(check) changed the directory from %d to %d entries", len(before), len(after))
			}
		})
	}
}
